/** Sorteia uma frase aleatória de uma lista */
function pickRandom(arr: readonly string[]): string {
  const index = Math.floor(Math.random() * arr.length);
  return arr[index] ?? arr[0];
}

export type PhraseCategory = keyof Omit<typeof PHRASE_BANK, 'marcos'>;

/** Obtém uma frase aleatória da categoria especificada */
export function getRandomPhrase(category: PhraseCategory): string {
  const list = PHRASE_BANK[category];
  if (Array.isArray(list)) {
    return pickRandom(list);
  }
  return 'Muito bem!';
}

/** Escolhe o melhor elogio baseado na sequência de acertos consecutivos */
export function getPraisePhrase(streakInLesson: number): string {
  if (streakInLesson >= 3) {
    return getRandomPhrase('acertouCombo');
  }
  if (streakInLesson === 2) {
    return getRandomPhrase('acertouReforco');
  }
  return getRandomPhrase('acertouSimples');
}

/** Escolhe a melhor resposta de incentivo em caso de erro */
export function getGentleErrorPhrase(errorCount: number): string {
  if (errorCount >= 2) {
    return getRandomPhrase('erroRecorrente');
  }
  return getRandomPhrase('erroLeve');
}
